

CREATE TABLE PROVINCES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    CAPITAL VARCHAR(100),
    DESCRIPTION VARCHAR(2000),
    CREATED_DATE TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE DISTRICT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DISTRICT_NAME VARCHAR(255),
    PROVINCE BIGINT NOT NULL,
    DESCRIPTION VARCHAR(255),
    CREATED_DATE TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_DISTRICT_PROVINCE FOREIGN KEY (PROVINCE) REFERENCES PROVINCES (ID)
);
CREATE INDEX IDX_DISTRICT_PROVINCE ON DISTRICT (PROVINCE);

CREATE TABLE LOCALLEVEL (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(255),
    DISTRICT_ID BIGINT,
    CREATED_DATE TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_LOCALLEVEL_DISTRICT FOREIGN KEY (DISTRICT_ID) REFERENCES DISTRICT (ID)
);
CREATE INDEX IDX_LOCALLEVEL_DISTRICT_ID ON LOCALLEVEL (DISTRICT_ID);

